-- 월별 발령 통계 (배치)
SELECT d.DEPT_NM, COUNT(*) AS CNT
  FROM HR_APPNT a
  JOIN HR_DEPT d ON d.DEPT_CD = a.AFT_DEPT_CD
 WHERE a.APPNT_DT BETWEEN '2026-01-01' AND '2026-01-31'
 GROUP BY d.DEPT_NM;

